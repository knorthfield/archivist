import AppKit
import Testing
@testable import Archivist

@MainActor
struct ClipboardMonitorTests {
    let environment = TestEnvironment()
    var monitor: ClipboardMonitor { environment.monitor }
    var texts: [String] { environment.store.items.map(\.text) }

    init() {
        // The monitor ignores the contents that were on the clipboard before it started.
        _ = environment.monitor
    }

    @Test func aNewCopyIsSavedOnce() {
        environment.copy("a")
        monitor.check(sourceApp: safari)
        monitor.check(sourceApp: safari)
        #expect(texts == ["a"])
        #expect(environment.store.items.first?.sourceAppBundleID == "com.apple.Safari")
    }

    @Test func aCopyFromAnIgnoredAppIsNotSaved() {
        environment.copy("secret")
        monitor.check(sourceApp: SourceApp(bundleID: "com.apple.Passwords", name: "Passwords"))
        #expect(texts.isEmpty)
    }

    @Test(arguments: ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
                      "org.nspasteboard.ConcealedType", "com.agilebits.onepassword"])
    func markedContentIsNotSaved(marker: String) {
        environment.copy("secret", markers: [marker])
        monitor.check(sourceApp: safari)
        #expect(texts.isEmpty)
    }

    @Test func markedContentIsSavedWhenTheSettingsAreOff() {
        environment.defaults.set(false, forKey: Settings.ignoreTransientContent)
        environment.defaults.set(false, forKey: Settings.ignoreConfidentialContent)
        environment.copy("a", markers: ["org.nspasteboard.TransientType"])
        monitor.check(sourceApp: safari)
        environment.copy("b", markers: ["org.nspasteboard.ConcealedType"])
        monitor.check(sourceApp: safari)
        #expect(texts == ["b", "a"])
    }

    @Test func nothingIsSavedWhileTheMonitorIsPaused() {
        let start = Date(timeIntervalSince1970: 1000)
        monitor.pause(until: start + 60)
        environment.copy("a")
        monitor.check(sourceApp: safari, now: start + 30)
        #expect(texts.isEmpty)

        // The copy from the pause is not saved later.
        monitor.check(sourceApp: safari, now: start + 61)
        #expect(!monitor.isPaused)
        #expect(texts.isEmpty)

        environment.copy("b")
        monitor.check(sourceApp: safari, now: start + 62)
        #expect(texts == ["b"])
    }

    @Test func theClipboardDataOfArchivistIsNotANewCopy() {
        environment.copy("a")
        monitor.ignoreCurrentContents()
        monitor.check(sourceApp: safari)
        #expect(texts.isEmpty)
    }
}
