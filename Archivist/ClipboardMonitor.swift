import AppKit
import Observation

/// Looks at the clipboard twice each second and saves each new copy in the history.
@MainActor
@Observable
final class ClipboardMonitor {
    /// Apps put these types on the clipboard to tell clipboard managers about the data (nspasteboard.org).
    static let transientTypes: Set = ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
    static let confidentialTypes: Set = ["org.nspasteboard.ConcealedType", "com.agilebits.onepassword"]

    /// `.distantFuture` while the monitor is paused until the user resumes it.
    private(set) var pausedUntil: Date?
    var isPaused: Bool { pausedUntil != nil }

    @ObservationIgnored private let pasteboard: NSPasteboard
    @ObservationIgnored private let store: ItemStore
    @ObservationIgnored private let defaults: UserDefaults
    @ObservationIgnored private var lastChangeCount: Int
    @ObservationIgnored private var timer: Timer?

    init(pasteboard: NSPasteboard = .general, store: ItemStore, defaults: UserDefaults = .standard) {
        self.pasteboard = pasteboard
        self.store = store
        self.defaults = defaults
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated {
                let app = NSWorkspace.shared.frontmostApplication
                let sourceApp = app?.bundleIdentifier.map { SourceApp(bundleID: $0, name: app?.localizedName ?? $0) }
                self?.check(sourceApp: sourceApp)
            }
        }
    }

    func pause(until date: Date) {
        pausedUntil = date
    }

    func resume() {
        pausedUntil = nil
    }

    /// Archivist calls this after it writes to the clipboard, so that its own data is not a new copy.
    func ignoreCurrentContents() {
        lastChangeCount = pasteboard.changeCount
    }

    func check(sourceApp: SourceApp?, now: Date = .now) {
        if let pausedUntil, now >= pausedUntil { resume() }
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        guard !isPaused else { return }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard shouldSave(types: types, sourceBundleID: sourceApp?.bundleID) else { return }
        let contents = PasteboardContents(pasteboard: pasteboard)
        guard let item = store.add(contents, sourceApp: sourceApp, date: now) else { return }
        if item.kind == .image, item.imageText == nil, let imageData = contents.imageData {
            Task {
                let text = await ImageTextRecognizer.text(in: imageData)
                store.setImageText(text, of: item.id)
            }
        }
    }

    func shouldSave(types: Set<String>, sourceBundleID: String?) -> Bool {
        if let sourceBundleID, defaults.stringArray(forKey: Settings.ignoredApps)?.contains(sourceBundleID) == true {
            return false
        }
        if defaults.bool(forKey: Settings.ignoreTransientContent), !types.isDisjoint(with: Self.transientTypes) {
            return false
        }
        if defaults.bool(forKey: Settings.ignoreConfidentialContent), !types.isDisjoint(with: Self.confidentialTypes) {
            return false
        }
        return true
    }
}
